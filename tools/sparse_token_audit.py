"""Audit candidate atomic tokens in chunked corpora before locking BM25 tokenizer rules.

Applies the 4 proposed regex rules across every section-tier chunk JSON, counts
occurrences per matched token, and writes a frequency-sorted report for human
review. The goal: validate that the rules catch what they should and don't catch
junk.

Tokenizer rules (DRAFT):
  R1: dotted numerics       \\d+(\\.\\d+)+
  R2: all-caps acronyms     \\b[A-Z]{2,8}\\b      (2-8 char, word-boundary)
  R3: hyphenated codes      \\b[A-Z]+-\\d+\\b
  R4: all-caps + digit      \\b[A-Z]+\\d+\\b      (e.g. BEACON5)

Output: docs/sparse_token_audit.md
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

CHUNK_FILES = {
    "olg": PROJECT_ROOT / "index" / "olg" / "section_chunks.json",
    "cmr": PROJECT_ROOT / "index" / "cmr" / "section_chunks.json",
    "fns": PROJECT_ROOT / "index" / "fns" / "section_chunks.json",
    "cfr": PROJECT_ROOT / "index" / "cfr" / "section_chunks_context.json",
}

REPORT_PATH = PROJECT_ROOT / "docs" / "sparse_token_audit.md"

RULES = {
    "R1_dotted_numerics":      re.compile(r"\b\d+(?:\.\d+)+\b"),
    "R2_caps_acronyms_2_8":    re.compile(r"\b[A-Z]{2,8}\b"),
    "R3_hyphenated_codes":     re.compile(r"\b[A-Z]+-\d+\b"),
    "R4_caps_with_digit":      re.compile(r"\b[A-Z]+\d+\b"),
}


def load_chunks(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, list) else data.get("chunks", [])


def chunk_text(chunk: dict) -> str:
    """Extract searchable text from a chunk regardless of source schema."""
    parts = []
    for key in ("text", "content", "body", "context_prefix"):
        v = chunk.get(key)
        if isinstance(v, str):
            parts.append(v)
    return "\n".join(parts) if parts else json.dumps(chunk)


def audit_source(name: str, chunks: list[dict]) -> dict[str, Counter]:
    """For one source, count atomic-token candidates per rule."""
    counters = {rule: Counter() for rule in RULES}
    chunks_with_match = {rule: 0 for rule in RULES}

    for ch in chunks:
        text = chunk_text(ch)
        for rule, regex in RULES.items():
            matches = regex.findall(text)
            if matches:
                chunks_with_match[rule] += 1
                counters[rule].update(matches)

    return counters, chunks_with_match


def write_report(per_source: dict[str, tuple[dict, dict, int]]) -> None:
    REPORT_PATH.parent.mkdir(exist_ok=True)
    lines: list[str] = []
    lines.append("# Sparse Token Audit (Phase 3 tokenizer validation)")
    lines.append("")
    lines.append("Generated by `tools/sparse_token_audit.py`. Counts candidate atomic tokens per draft tokenizer rule, per source. Reviewer goal: confirm the rules catch the right things and don't pick up junk that should be tokenized normally.")
    lines.append("")
    lines.append("**Rules under review**:")
    lines.append("- R1 dotted numerics: `\\d+(\\.\\d+)+` — section refs (363.140, 1021.5)")
    lines.append("- R2 caps acronyms (2-8 chars): `[A-Z]{2,8}` — ABAWD, BEACON, EAEDC, etc.")
    lines.append("- R3 hyphenated codes: `[A-Z]+-\\d+` — VC-1, AP-1, SR-2")
    lines.append("- R4 caps+digit: `[A-Z]+\\d+` — BEACON5")
    lines.append("")
    lines.append("---")
    lines.append("")

    for source, (counters, chunks_with_match, total_chunks) in per_source.items():
        lines.append(f"## {source.upper()}")
        lines.append("")
        lines.append(f"Total section chunks scanned: **{total_chunks:,}**")
        lines.append("")
        for rule_name in RULES:
            ctr = counters[rule_name]
            unique = len(ctr)
            total_matches = sum(ctr.values())
            chunks_hit = chunks_with_match[rule_name]
            chunk_pct = (chunks_hit / total_chunks * 100) if total_chunks else 0
            lines.append(f"### {rule_name}")
            lines.append(f"- Unique tokens: **{unique:,}**")
            lines.append(f"- Total occurrences: **{total_matches:,}**")
            lines.append(f"- Chunks containing >=1 match: **{chunks_hit:,}** ({chunk_pct:.1f}%)")
            lines.append("")

            top = ctr.most_common(50)
            if top:
                lines.append("Top 50 by frequency:")
                lines.append("")
                lines.append("| token | count |")
                lines.append("|---|---|")
                for token, count in top:
                    lines.append(f"| `{token}` | {count:,} |")
                lines.append("")

            # Show a tail sample for low-frequency hits — these surface false positives
            tail = [t for t in ctr.most_common() if ctr[t[0]] == 1][:30]
            if tail:
                lines.append("<details><summary>Sample of singletons (count=1) — likely candidates for false positives</summary>")
                lines.append("")
                lines.append(", ".join(f"`{t}`" for t, _ in tail))
                lines.append("")
                lines.append("</details>")
                lines.append("")
        lines.append("---")
        lines.append("")

    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote report: {REPORT_PATH}")


def main() -> None:
    per_source: dict[str, tuple[dict, dict, int]] = {}
    for source, path in CHUNK_FILES.items():
        chunks = load_chunks(path)
        if not chunks:
            print(f"[skip] {source}: no chunks at {path}")
            continue
        print(f"[scan] {source}: {len(chunks):,} chunks from {path.name}")
        counters, chunks_with_match = audit_source(source, chunks)
        per_source[source] = (counters, chunks_with_match, len(chunks))

    write_report(per_source)

    # Console summary
    print()
    print("=== Summary ===")
    for source, (counters, _, total) in per_source.items():
        print(f"\n{source.upper()} ({total:,} chunks)")
        for rule in RULES:
            ctr = counters[rule]
            print(f"  {rule:30} unique={len(ctr):>5}  occurrences={sum(ctr.values()):>7,}")


if __name__ == "__main__":
    main()
